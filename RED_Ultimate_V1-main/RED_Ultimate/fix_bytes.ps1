function Replace-Bytes($bytes, $search, $replace) {
    $newBytes = @()
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        $match = $true
        for ($j = 0; $j -lt $search.Length; $j++) {
            if ($i + $j -ge $bytes.Length -or $bytes[$i + $j] -ne $search[$j]) {
                $match = $false
                break
            }
        }
        if ($match) {
            $newBytes += $replace
            $i += $search.Length - 1
        } else {
            $newBytes += $bytes[$i]
        }
    }
    return $newBytes
}

